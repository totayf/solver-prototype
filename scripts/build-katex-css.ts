/**
 * Writes KaTeX's layout CSS (from the installed `katex` package) into the
 * player as a string module, without its @font-face rules: those point at
 * relative font URLs Metro can't bundle (and warns about on every cold
 * build). The fonts themselves are bundled by `player-fonts.ts`.
 *
 *   bun scripts/build-katex-css.ts          # after upgrading katex
 *
 * `tests/katex-css.test.ts` fails when the file is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const KATEX_CSS_MODULE = fileURLToPath(
  new URL(
    "../src/widgets/lesson-player/ui/katex-css.generated.ts",
    import.meta.url,
  ),
);

export function katexCssModule(): string {
  const pkg = JSON.parse(
    readFileSync(require.resolve("katex/package.json"), "utf8"),
  ) as { version: string };
  const css = readFileSync(require.resolve("katex/dist/katex.min.css"), "utf8")
    .replace(/@font-face\{[^}]*\}/g, "")
    .trim();
  return [
    `// Generated by scripts/build-katex-css.ts from katex@${pkg.version}. Do not edit.`,
    "// KaTeX layout rules without @font-face; the fonts come from player-fonts.ts.",
    `export const KATEX_CSS = ${JSON.stringify(css)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(KATEX_CSS_MODULE, katexCssModule());
  console.log(`wrote ${path.relative(process.cwd(), KATEX_CSS_MODULE)}`);
}
